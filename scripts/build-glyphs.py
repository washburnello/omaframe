def match_rule(name, entry):
    """Whole-token match, or '_'-delimited compound match."""
    if "_" not in entry:
        return entry in name.split("_")
    return f"_{entry}_" in f"_{name}_"


def categorize(name):
    if name in OVERRIDES:
        return OVERRIDES[name]
    for cat, toks in RULES:
        if cat == "Misc":
            continue
        if any(match_rule(name, t) for t in toks):
            return cat
    return "Misc"


def main():
    import os
    glyphs = json.load(open(GLYPHNAMES))
    entries = {}  # codepoint -> (glyph, name, category)
    # 1. FA + Octicons from glyphnames.
    for key, val in glyphs.items():
        if key == "METADATA":
            continue
        if key.startswith("fa-"):
            name = key[3:]
        elif key.startswith("oct-"):
            entries[int(val["code"], 16)] = (val["char"], key[4:], "Octicons")
            continue
        else:
            continue
        cp = int(val["code"], 16)
        cat = categorize(name)
        if cp not in entries:
            entries[cp] = (val["char"], name, cat)
    # 2. Carried curated entries from nerd.txt (prefer friendly names).
    for line in open(NERD_TXT):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) < 3:
            continue
        glyph, name, code = parts[0], parts[1], parts[2].lstrip("U+")
        try:
            cp = int(code, 16)
        except ValueError:
            continue
        ch = chr(cp)
        if ch != glyph:
            print(f"WARN: glyph/char mismatch {name} {code}", file=sys.stderr)
        norm = name.replace("-", "_")
        cat = categorize(norm)
        entries[cp] = (ch, name, cat)
    print(f"total unique codepoints: {len(entries)}", file=sys.stderr)
    print(Counter(c for _, _, c in entries.values()), file=sys.stderr)
    # 3. Verify: installed font coverage + single-cell width.
    ok, dropped = [], []
    for cp in sorted(entries):
        ch, name, cat = entries[cp]
        if unicodedata.east_asian_width(ch) in ("W", "F"):
            dropped.append((name, f"U+{cp:04X}", "wide"))
            continue
        r = subprocess.run(["fc-match", f":charset={cp:04X}", "family"],
                           capture_output=True, text=True, timeout=30)
        fam = r.stdout.strip()
        if not fam:
            dropped.append((name, f"U+{cp:04X}", "no font"))
            continue
        ok.append((cp, ch, name, cat, fam))
    print(f"kept {len(ok)}, dropped {len(dropped)}", file=sys.stderr)
    for d in dropped[:50]:
        print("DROP:", d, file=sys.stderr)
    # 4. Category census for review.
    print(Counter(c for _, _, _, c, _ in ok), file=sys.stderr)
    # 5. Emit sorted by category then name.
    with open(OUT, "w") as f:
        f.write("# omaframe glyph palette: categorized FA + Octicons + curated extras.\n")
        f.write("# Generated by scripts/build-glyphs.py. Format: <glyph>  <name>  <U+CODE>  <Category>\n")
        for cp, ch, name, cat, fam in sorted(ok, key=lambda t: (t[3], t[2])):
            f.write(f"{ch}  {name}  U+{cp:04X}  {cat}\n")
    print(f"wrote {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
